/* ────────────────────────────────────────────────────────────────────────
   Generates public/robots.txt and public/sitemap.xml from the project data.

   Both are generated rather than hand-written because a sitemap is exactly
   the kind of file that silently stops being true: a project gets a case
   study, nobody remembers this file, and the sitemap advertises eight pages
   of a nine-page site. Driving it off `projects` means the only way to add a
   route is to add the data the route is built from.

   Runs as `prebuild`, so a deploy cannot ship a stale one.
   ──────────────────────────────────────────────────────────────────────── */

import { writeFileSync, mkdirSync } from 'node:fs'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'
import { projects } from '../src/data/projects.js'

/* The deployed origin. The canonical link in index.html must match this —
   it previously pointed at manan-kochhar.vercel.app, which is a 404, which
   told every crawler the authoritative copy of the site was a missing page. */
const ORIGIN = process.env.SITE_ORIGIN ?? 'https://manan-portfolio-03.vercel.app'

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const today = new Date().toISOString().slice(0, 10)

const routes = ['/', ...projects.filter((p) => p.study).map((p) => `/work/${p.id}`)]

const robots = `# Generated by scripts/gen-seo.mjs — do not edit by hand.
User-agent: *
Allow: /

Sitemap: ${ORIGIN}/sitemap.xml
`

const sitemap = `<?xml version="1.0" encoding="UTF-8"?>
<!-- Generated by scripts/gen-seo.mjs — do not edit by hand. -->
<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">
${routes
  .map(
    (r) => `  <url>
    <loc>${ORIGIN}${r}</loc>
    <lastmod>${today}</lastmod>
    <priority>${r === '/' ? '1.0' : '0.8'}</priority>
  </url>`
  )
  .join('\n')}
</urlset>
`

mkdirSync(resolve(root, 'public'), { recursive: true })
writeFileSync(resolve(root, 'public/robots.txt'), robots)
writeFileSync(resolve(root, 'public/sitemap.xml'), sitemap)

console.log(`gen-seo: ${routes.length} routes → public/robots.txt, public/sitemap.xml`)
